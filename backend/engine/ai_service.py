def adapt_quote_first(response: QuoteFirstAnalysis, source_text: str = "") -> ProviderAnalysis:
    """Assign stable IDs without trusting provider-generated references."""
    evidence, identifiers = [], {}
    def references(quotes):
        output = []
        for quote in quotes:
            # Deduplicate exact strings only; never normalize the stored quotation.
            if quote not in identifiers:
                ref = f"e{len(evidence)+1}"
                identifiers[quote] = ref
                evidence.append(Evidence(id=ref, excerpt=quote))
            output.append(identifiers[quote])
        return list(dict.fromkeys(output))
    # Only explicit global applicability forms are attached deterministically.
    # The original clause is visible on the same item and reviewed as context;
    # no generated replacement condition or unstated eligibility is invented.
    global_conditions=[m.group() for pattern in (_GLOBAL_PAIR,_ENGLISH_ELIGIBILITY)
                       for m in pattern.finditer(source_text)]
    declared_scope = any(_quote_found(clause, item.text + " " + " ".join(item.source_conditions))
                         for item in response.explanation for clause in global_conditions)
    def claim(item, section):
        conditions=list(item.source_conditions)
        if not declared_scope and (section != "explanation" or _REQUIREMENT_CUE.search(item.text) or _FEE_CUE.search(item.text)):
            conditions=global_conditions+conditions
        deduplicated={}
        for condition in conditions:
            deduplicated.setdefault(normalize_whitespace(condition).rstrip("।. "),condition)
        conditions=list(deduplicated.values())
        return Claim(text=item.text,status=item.status,source_conditions=conditions,
                     evidence_ids=references(item.source_quotes+conditions))
    sections = {name:[claim(item,name) for item in getattr(response,name)]
                for name in ("explanation","steps","documents")}
    timing = FeesAndDeadlines(**{name:[claim(item,name) for item in getattr(response.fees_and_deadlines,name)]
                                for name in ("fees","deadlines")})
    unknowns = [Uncertainty(**item.model_dump(exclude={"source_quotes"}),
                           evidence_ids=references(item.source_quotes)) for item in response.unknowns]
    return ProviderAnalysis(**sections, fees_and_deadlines=timing, unknowns=unknowns, evidence=evidence)



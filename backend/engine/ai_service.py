def _opposing_age_rules(source_text: str) -> list[tuple[str, str, str, str]]:
    """Find only exclusive >=N and <N rules in one named service/group.

    This intentionally does not interpret other eligibility prose or reconcile
    different age thresholds. Unclear service/applicant scope is left alone.
    """
    conflicts = []
    for line in source_text.splitlines():
        service = _SERVICE_LINE.fullmatch(line.strip())
        if not service:
            continue
        rules: dict[tuple[str, str], dict[str, str]] = {}
        for sentence in re.findall(r"[^।。]+(?:[।。]|$)", service["body"]):
            sentence = sentence.strip()
            match = _DIRECT_AGE_RULE.search(sentence)
            if not match:
                continue
            prefix = sentence[:match.start()]
            group = re.search(r"([\u0980-\u09FF]+)\s+আবেদনকারীদের\s+(?:মধ্যে|জন্য)\s*$", prefix)
            if "আবেদনকারীদের" in prefix and group is None:
                continue  # Applicant group is unclear; do not compare it.
            applicant_group = group.group(1) if group else "unspecified"
            age = next(iter(_numeric_literals(match["age"])))
            direction = "minimum" if "বেশি" in match["direction"] else "below"
            rules.setdefault((applicant_group, age), {})[direction] = sentence
        for both in rules.values():
            if "minimum" in both and "below" in both:
                conflicts.append((service["service"], service["name"].strip(), both["minimum"], both["below"]))
    return conflicts


def estimate_input_tokens(source_message: str, output_language: Language = "bn") -> int:
    """Conservative UTF-8 byte proxy, not a provider tokenizer or quota lookup.

    Include prompt, schema and envelope overhead without a second countTokens API
    request. Actual provider usage/limits remain authoritative.
    """
    schema = json.dumps(QuoteFirstAnalysis.model_json_schema(), ensure_ascii=False)
    return len((source_message + build_system_prompt(output_language) + schema).encode("utf-8")) + 2048


def check_evidence(
    response: ProviderAnalysis,
    source_text: str,
    *,
    source_type: SourceType,
    source_url: str | None,
    model: str,
    output_language: Language = "bn",
) -> AnalysisResult:
    """Check narrow quote support, not semantic entailment or authenticity."""
    source = _quotation_key(source_text)
    notices = NOTICES[output_language]
    labels = notices["labels"]
    ids = [item.id for item in response.evidence]
    if len(set(ids)) != len(ids):
        raise AnalysisError("malformed_response", "AI উত্তরে উদ্ধৃতির পরিচয় স্পষ্ট নয়। আবার চেষ্টা করুন।")
    evidence = [
        CheckedEvidence(**(item.model_dump() | {
            "excerpt": _original_excerpt(item.excerpt, source_text)
            if _quote_found(item.excerpt, source_text) else item.excerpt,
        }), excerpt_found=_quote_found(item.excerpt, source_text))
        for item in response.evidence
    ]
    found = {item.id for item in evidence if item.excerpt_found}
    excerpts = {item.id: item.excerpt for item in evidence if item.excerpt_found}
    unknowns: list[Uncertainty] = []
    warning_indices: dict[tuple[str, str], int] = {}

    def add_unknown(item: Uncertainty) -> None:
        # Normalize only known, unqualified absence notices. Conditional notices
        # and contradictory facts retain their wording and evidence references.
        category = _missing_notice_category(item.text) if item.kind == "missing" else None
        if category:
            item = item.model_copy(update={"category":{"কাগজপত্র":"documents","ফি":"fees","সময়সীমা":"deadlines"}.get(category,"general"), "reason_code":"source_absent"})
        text = notices["missing"].format(label=labels[category]) if category else item.text
        key = (item.kind, "general" if text.startswith(tuple(notices["claim_warning"].format(status=notices[status],claim="") for status in ("unsupported","contradictory"))) else item.category, item.reason_code, _notice_key(text))
        if key in warning_indices:
            index = warning_indices[key]
            previous = unknowns[index]
            refs = list(dict.fromkeys(previous.evidence_ids + item.evidence_ids))
            unknowns[index] = previous.model_copy(update={"evidence_ids":refs})
        else:
            warning_indices[key] = len(unknowns)
            unknowns.append(item.model_copy(update={"text":text,"evidence_ids":list(dict.fromkeys(item.evidence_ids))}))

    def add_missing(label: str, refs: list[str] | None = None) -> None:
        category = {"কাগজপত্র":"documents","ফি":"fees","সময়সীমা":"deadlines"}.get(label,"general")
        if any(u.kind == "missing" and u.category == category and set(u.evidence_ids) == set(refs or []) for u in unknowns):
            return
        add_unknown(Uncertainty(kind="missing", text=notices["missing"].format(label=labels[label]), evidence_ids=refs or []))

    for item in response.unknowns:
        add_unknown(item)
    age_conflicts = []
    named_services = [
        (match["service"], match["name"].strip())
        for line in source_text.splitlines()
        if (match := _SERVICE_LINE.fullmatch(line.strip()))
    ]
    for service_id, service_name, minimum, below in _opposing_age_rules(source_text):
        refs = [
            item.id for item in evidence if item.excerpt_found and
            (_quotation_key(minimum) in _quotation_key(item.excerpt) or
             _quotation_key(below) in _quotation_key(item.excerpt))
        ]
        add_unknown(Uncertainty(
            kind="contradiction",
            text=notices["age_conflict"].format(service_id=service_id, service_name=service_name, minimum=minimum, below=below)[:4000],
            evidence_ids=refs,
        ))
        age_conflicts.append((service_id, service_name, set(refs)))
    disputed = {
        ref for item in response.unknowns if item.kind == "contradiction"
        for ref in item.evidence_ids
    }
    uncertain = {
        ref for item in response.unknowns if item.kind == "unverified"
        for ref in item.evidence_ids
    }

    def check(claims: list[Claim], *, fact_only: bool = False, context: str | None = None, category: Category = "general") -> list[CheckedClaim]:
        checked = []
        for claim in claims:
            supported = bool(claim.evidence_ids) and all(ref in found for ref in claim.evidence_ids)
            cited_text = " ".join(excerpts.get(ref, "") for ref in claim.evidence_ids)
            numeric_support = _numeric_literals(claim.text) <= _numeric_literals(cited_text)
            condition_support=all(_quote_found(condition, source_text) and _quote_found(condition, cited_text)
                                  for condition in claim.source_conditions)
            supported=supported and condition_support
            claim=claim.model_copy(update={"source_conditions":[_original_excerpt(c,source_text) if _quotation_key(c) in source else c for c in claim.source_conditions]})
            age_disputed = any(
                refs.intersection(claim.evidence_ids) and
                ("বয়স" in claim.text or "যোগ্য" in claim.text or re.search(r"\b(?:age|aged|eligib\w*)\b", claim.text, re.I)) and
                not any(
                    other_id != service_id and (other_name in claim.text or f"সেবা {other_id}" in claim.text or f"service {other_id}".casefold() in claim.text.casefold())
                    for other_id, other_name in named_services
                )
                for service_id, name, refs in age_conflicts
            )
            status = (
                "contradictory" if claim.status == "contradictory" or disputed.intersection(claim.evidence_ids) or age_disputed
                else "quotation_matched" if supported and numeric_support and not uncertain.intersection(claim.evidence_ids) and claim.status == "source_stated"
                else "unsupported"
            )
            missing_category = _missing_notice_category(claim.text, context) if context else None
            if missing_category and status != "contradictory":
                add_missing(missing_category, claim.evidence_ids)
                if claim.evidence_ids and not supported:
                    add_unknown(Uncertainty(kind="unverified", text=notices["missing_quote"].format(label=labels[missing_category]), evidence_ids=claim.evidence_ids))
                # An absence notice is never promoted to a verified factual item.
                continue
            if not fact_only or status == "quotation_matched":
                checked.append(CheckedClaim(**claim.model_dump(), evidence_status=status,
                    withholding_reason=None if status == "quotation_matched" else ("quotation_mismatch" if not supported else "numeric_mismatch" if not numeric_support else "unsupported_interpretation")))
            if status != "quotation_matched":
                add_unknown(Uncertainty(
                    kind="contradiction" if status == "contradictory" else "unverified",
                    category=category, reason_code="quotation_mismatch" if not supported else "numeric_mismatch" if not numeric_support else "unsupported_interpretation",
                    text=notices["claim_warning"].format(status=notices["contradictory" if status == "contradictory" else "unsupported"], claim=claim.text)[:4000],
                    evidence_ids=claim.evidence_ids,
                ))
        return checked

    explanation = check(response.explanation)
    steps = check(response.steps, category="steps")
    documents = check(response.documents, category="documents")
    fees = check(response.fees_and_deadlines.fees, fact_only=True, context="ফি", category="fees")
    deadlines = check(response.fees_and_deadlines.deadlines, fact_only=True, context="সময়সীমা", category="deadlines")
    # Empty-category assessments go through review before public missing copy.
    # Existing uncertain interpretations take precedence over missing notices.
    from result_metadata import extraction_gap_notice
    for label, category, claims in (("steps","steps",response.steps),
            ("কাগজপত্র","documents",response.documents),
            ("ফি","fees",response.fees_and_deadlines.fees),
            ("সময়সীমা","deadlines",response.fees_and_deadlines.deadlines)):
        prefixes = (f"{label}:", f'{NOTICES["en"]["labels"].get(label,label)}:')
        if not claims and not any(item.category == category or item.text.startswith(prefixes) for item in unknowns):
            add_unknown(Uncertainty(**extraction_gap_notice(category, output_language)))
    for item in evidence:
        if not item.excerpt_found:
            add_unknown(Uncertainty(kind="unverified", text=notices["quote_unmatched"].format(id=item.id), evidence_ids=[item.id]))
    for item in response.unknowns:
        if any(ref not in found for ref in item.evidence_ids):
            add_unknown(Uncertainty(kind="unverified", text=notices["uncertainty_unmatched"].format(text=item.text)[:4000], evidence_ids=item.evidence_ids))
    # Suppress only uncited, recognized whole-category boilerplate alongside an
    # already supported requirement. Preserve cited absence claims for review
    # (the source itself may conflict), conditional notices and all warnings.
    supplied_categories = {
        label for label, claims in (("কাগজপত্র", documents), ("ফি", fees), ("সময়সীমা", deadlines))
        if any(claim.evidence_status == "quotation_matched" and
               _missing_notice_category(claim.text, label) is None for claim in claims)
    }
    unknowns = [item for item in unknowns if not (
        item.kind == "missing" and not item.evidence_ids and
        _missing_notice_category(item.text) in supplied_categories
    )]
    return AnalysisResult(
        explanation=explanation, steps=steps, documents=documents,
        fees_and_deadlines=CheckedFeesAndDeadlines(fees=fees, deadlines=deadlines),
        unknowns=unknowns, evidence=evidence,
        source_type=source_type, source_url=source_url, model=model, output_language=output_language,
    )


def review_candidates(result: AnalysisResult) -> dict[str, Claim | Uncertainty]:
    sections = {
        "explanation": result.explanation, "steps": result.steps,
        "documents": result.documents, "fees": result.fees_and_deadlines.fees,
        "deadlines": result.fees_and_deadlines.deadlines, "unknowns": result.unknowns,
    }
    candidates = {f"{section}:{i}": item for section, items in sections.items() for i, item in enumerate(items)}
    if len(candidates) > 120:
        raise AnalysisError("malformed_response", "Too many claims for complete semantic review.")
    return candidates


def build_review_message(result, source_text, *, question=None, source_scope=None):
    candidates = review_candidates(result)
    return json.dumps({"source_text": source_text, "question": question,
        "source_scope": source_scope,
        "completeness_policy": "Treat all sections as one plan. Dates in deadlines, fees in fees, and global eligibility in explanation/source_conditions qualify concise steps/documents without repetition. Preserve local exceptions and OR/negation.",
        "candidates": [{"id": key, "section": key.split(":")[0], "text": item.text,
                        "kind": getattr(item, "kind", "factual"),
                        **({"source_conditions":item.source_conditions} if isinstance(item,Claim) else {}),
                        **({"category":item.category,"reason_code":item.reason_code} if isinstance(item,Uncertainty) else {})}
                       for key, item in candidates.items()]}, ensure_ascii=False, separators=(",", ":"))


_FEE_CUE = re.compile(r"(?<!\w)(?:ফি|ভ্যাট|fee|fees|VAT)(?!\w)", re.I)
# Extractive routing for the recorded official delivery clauses only. Require the
# entire domestic/tier/conditional statement and a matching original citation;
# this neither infers a submission cutoff nor approves a paraphrase's semantics.
_PASSPORT_DELIVERY = re.compile(
    r"দেশের অভ্যন্তরে (?:অতি জরুরী|জরুরী|রেগুলার) পাসপোর্ট প্রাপ্তির লক্ষ্যে "
    r"অন্যান্য সকল তথ্য সঠিক থাকা সাপেক্ষে [০-৯0-9]+ কর্মদিবসের মধ্যে পাসপোর্ট প্রদান করা হবে।")
# A document requirement need not contain a submission verb. Treat noun/predicate
# requirements identically, while _information_only keeps number-entry distinct.
_REQUIREMENT_CUE = re.compile(r"দাখিল|জমা|প্রদর্শন|সংযোজন|আপলোড|বাধ্যতামূলক|প্রয়োজন|প্রয়োজন|লাগবে|আবশ্যক|\b(?:submit|present|attach|upload|provide|required|mandatory|compulsory|needed|need|must)\b", re.I)
_DOCUMENT_CODE = re.compile(r"\(([A-Z][A-Z0-9]{1,7})(?:[ )])")
_SCOPE_CUE = re.compile(r"বছর|বয়স|বয়স|হলে|ক্ষেত্রে|অথবা|ব্যতীত|ছাড়া|ছাড়া|\b(?:if|unless|except|under|aged|or)\b", re.I)
_GLOBAL_PAIR = re.compile(r"শুধু\s+([^\n।]+?)\s*[—–]\s*দুই\s+শর্তই\s+পূরণ\s+হলে\s+আবেদন\s+করা\s+যাবে")
_DOCUMENT_ALIASES = {
    "NID": ("জাতীয় পরিচয়পত্র", "জাতীয় পরিচয়পত্র", "national identity", "national id"),
    "BRC": ("জন্মনিবন্ধন সনদ", "birth registration certificate"),
    "GO": ("সরকারি আদেশ", "government order"),
    "NOC": ("অনাপত্তি", "no objection certificate"),
}


def _document_entities(text):
    key = unicodedata.normalize("NFC", normalize_whitespace(text)).casefold()
    codes = {code for code in _DOCUMENT_CODE.findall(text)}
    for code, names in _DOCUMENT_ALIASES.items():
        if re.search(r"\b" + code.casefold() + r"\b", key) or any(
                unicodedata.normalize("NFC", name).casefold() in key for name in names):
            codes.add(code)
    return codes


def _information_only(text):
    return bool(re.search(r"নম্বর|\bnumber\b", text, re.I)) and not bool(
        re.search(r"কপি|অনুলিপি|মূল|\b(?:copy|photocopy|original)\b", text, re.I))


def _document_request(text, section):
    return section == "documents" or bool(_REQUIREMENT_CUE.search(text) and not _information_only(text))



def _district_student_scope(text: str) -> bool:
    """Bounded affirmative paraphrases of the observed two-part eligibility.

    This is a withholding guard, not an approval mechanism. It is consulted only
    when the source explicitly requires district residence AND current study.
    """
    key=normalize_whitespace(text).casefold()
    patterns=(
        r"(?:এই|উক্ত|নির্দিষ্ট)\s+জেলার\s+বাসিন্দা\s+(?:এবং|ও)\s+বর্তমান(?:ে)?\s+শিক্ষার্থী",
        r"(?:এই|উক্ত|নির্দিষ্ট)\s+জেলায়\s+বসবাসকারী\s+বর্তমান(?:ে)?\s+শিক্ষার্থী",
        r"\bcurrent\s+students?\s+(?:who\s+)?(?:live|living|reside|residing)\s+in\s+this\s+district\b",
        r"\bresidents?\s+of\s+this\s+district\s+(?:and\s+(?:are\s+)?current\s+students?)\b",
        r"\b(?:you\s+live|living)\s+in\s+this\s+district\s+and\s+(?:are\s+)?(?:currently\s+)?a\s+student\b",
    )
    for pattern in patterns:
        match=re.search(pattern,key)
        if not match:
            continue
        before=key[max(0,match.start()-20):match.start()]
        after=key[match.end():]
        negated_before=re.search(r"(?:\bnot\s+(?:a\s+)?|না\s*)$",before)
        negated_or_broadened=re.match(r"\s*(?:or\b|অথবা|কিংবা|বা\s|না\s|নন|নয়|নয়)",after)
        denied_conditions=re.search(r"শর্ত(?:ই)?\s+পূরণ\s+(?:না|করেননি|হয়নি|হয়নি)|শর্ত(?:ই)?\s+পূরণকারী\s+(?:নন|নয়|নয়)",after[:120])
        if not (negated_before or negated_or_broadened or denied_conditions):
            return True
    return False


def _prior_certificate_exception(text: str) -> bool:
    """Recognize the explicit negative prior-submission condition, not its omission."""
    return bool(re.search(
        r"আগে\s+সনদ\s+জমা\s+না\s+দিয়ে\s+থাকলে|যদি\s+আগে\s+সনদ\s+জমা\s+না\s+দিয়ে\s+থাকেন|"
        r"\bunless\s+(?:you\s+have\s+)?(?:already|previously)\s+submitted\b|"
        r"\bif\s+(?:you\s+have\s+)?not\s+(?:already|previously)\s+submitted\b",text,re.I))


def _disability_fee_exception(text: str, source_clause: str) -> bool:
    """Allow affirmative equivalents only for this explicit source exemption."""
    if normalize_whitespace(source_clause) != "প্রতিবন্ধী আবেদনকারীদের ফি দিতে হবে না":
        return False
    return bool(re.search(
        r"প্রতিবন্ধী(?:\s+আবেদনকারী)?\s+না\s+হলে|প্রতিবন্ধী\s+(?:নন|নয়|নয়)\s+এমন\s+আবেদনকারী|"
        r"\bexcept\s+(?:for\s+)?(?:applicants?\s+with\s+disabilities|disabled\s+applicants?)\b|"
        r"\bunless\s+(?:you\s+are\s+)?disabled\b|"
        r"\bif\s+(?:you\s+are\s+)?not\s+disabled\b",text,re.I))


_ENGLISH_ELIGIBILITY = re.compile(r"\bOnly\s+([^.!?\n]{1,300}?)\s+may\s+apply\s*[.!?]", re.I)
_ENGLISH_DOCUMENT_ALTERNATIVE = re.compile(r"\b(certificate|document)\s+([A-Z0-9-]+)\s+OR\s+(certificate|document)\s+([A-Z0-9-]+)\b", re.I)


def scope_withholding_reason(item: Claim, section: str, source_text: str, supporting_text: str = "", *, shared_conditions=()) -> str | None:
    """Conservative source-contract cues, NEVER a test that approves semantics.

    Unknown grammar is not certified. Supported translations/paraphrases may be
    withheld; these cues do not replace AI review or establish universal safety.
    """
    condition_text = normalize_whitespace(item.text+" "+" ".join(item.source_conditions)+" "+" ".join(shared_conditions))
    primary_conflict=re.search(r"(?:বাসিন্দা|শিক্ষার্থী)\s+(?:না|নন|নয়|নয়)|\bnot\s+(?:a\s+)?(?:current\s+student|resident)",item.text,re.I)
    primary_or=re.search(r"বাসিন্দা\s+(?:অথবা|বা|কিংবা)\s+(?:বর্তমান(?:ে)?\s+)?শিক্ষার্থী|\bresidents?\s+of\s+this\s+district\s+or\s+current\s+students?",item.text,re.I)
    if (item.source_conditions or shared_conditions) and (primary_conflict or primary_or):
        return "global_scope"
    # The recorded source offers conditional domestic delivery, not a generic
    # promise. Routing alone is insufficient: withhold shortened versions in any
    # section, even under a wrong reviewer verdict. Unknown paraphrases may be
    # withheld; this bounded extractive contract does not infer their meaning.
    delivery_clauses = {m.group() for m in _PASSPORT_DELIVERY.finditer(_quotation_key(source_text))}
    if delivery_clauses and "পাসপোর্ট" in item.text and "কর্মদিবস" in item.text:
        if _quotation_key(item.text) not in delivery_clauses:
            return "delivery_scope"
    # Preserve the explicit paired resident/current-student eligibility in an
    # overview as well. This bounded actor cue withholds omissions/OR/negation;
    # it never supplies or translates eligibility that the source did not state.
    global_rules = list(_GLOBAL_PAIR.finditer(source_text))
    if section == "explanation" and global_rules and not (_REQUIREMENT_CUE.search(item.text) or _FEE_CUE.search(item.text)):
        for rule in global_rules:
            condition = rule.group(1)
            if "বাসিন্দা" in condition and "শিক্ষার্থী" in condition:
                text = item.text.casefold()
                concepts = (re.search(r"জেলা|\bdistrict\b", text), re.search(r"বাসিন্দা|\bresident", text),
                            re.search(r"বর্তমান|\bcurrent", text), re.search(r"শিক্ষার্থী|\bstudent", text),
                            re.search(r"এবং|\band\b", text))
                if (not all(concepts) and not _district_student_scope(condition_text)) or re.search(r"অথবা|কিংবা|(?<![\w\u0980-\u09ff])(?:বা|না|নয়|নয়|not|or)(?![\w\u0980-\u09ff])", text):
                    return "global_scope"
    if section == "explanation" and (_REQUIREMENT_CUE.search(item.text) or _FEE_CUE.search(item.text)):
        section = "steps"  # A requirement cannot evade scope checks by changing its section.
    if section not in ("steps", "documents", "fees", "deadlines"):
        return None
    for rule in _ENGLISH_ELIGIBILITY.finditer(source_text):
        # Bounded extractive applicability check, parallel to the Bangla form.
        # Matching this condition is necessary, never proof of entailment.
        condition = _quotation_key(rule.group(1)).casefold()
        text = _quotation_key(condition_text).casefold()
        known_pair = bool(re.fullmatch(r"current students? (?:who )?(?:live|living|reside|residing) in this district|residents? of this district and (?:are )?current students?",condition))
        equivalent = known_pair and _district_student_scope(condition_text)
        if (condition not in text and not equivalent) or re.search(r"\b(?:not|except)\s+"+re.escape(condition),text,re.I):
            return "global_scope"
    for alternative in _ENGLISH_DOCUMENT_ALTERNATIVE.finditer(source_text):
        left, right = alternative.group(2), alternative.group(4)
        mentions = section == "documents" or bool(re.search(r"certificate|document|সনদ|কাগজ",item.text,re.I))
        if mentions and (re.search(r"\b"+re.escape(left)+r"\b",item.text) or re.search(r"\b"+re.escape(right)+r"\b",item.text)):
            complete = re.search(re.escape(alternative.group(1))+r"\s+"+re.escape(left)+r"\s+or\s+"+re.escape(alternative.group(3))+r"\s+"+re.escape(right),item.text,re.I)
            if not complete:
                return "document_alternative"
    if re.search(r"certificate A OR certificate B unless already submitted", source_text, re.I) and re.search(r"certificate", item.text, re.I):
        if not re.search(r"unless already submitted|if (?:not|never) (?:previously |already )?submitted", condition_text, re.I):
            return "prior_submission"
    if re.search(r"applicants with disabilities pay no fee", source_text, re.I) and _FEE_CUE.search(item.text) and _numeric_literals(item.text):
        if not re.search(r"(?:not|unless|except).{0,45}(?:disabilit|disabled)|(?:disabilit|disabled).{0,35}(?:no fee|exempt)", condition_text, re.I):
            return "fee_exception"
    if re.search(r"must submit the application form even when exempt from fees", source_text, re.I) and re.search(r"application form", item.text, re.I):
        if re.search(r"do not|don't|need not|not (?:required|necessary)", item.text, re.I):
            return "form_submission_negation"
    for rule in _GLOBAL_PAIR.finditer(source_text):
        # This deliberately narrow, explicit global form has a stable source
        # condition. Requiring its literal affirmative form prevents AND -> OR
        # and undefined-group substitutions; it does not guess translations.
        required = normalize_whitespace(rule.group(1))
        affirmative = re.escape(required + " হলে") + r"(?=\s|[,।:]|$)"
        known_pair = bool(re.fullmatch(r"(?:এই|উক্ত|নির্দিষ্ট)\s+জেলার\s+বাসিন্দা\s+(?:এবং|ও)\s+বর্তমান(?:ে)?\s+শিক্ষার্থী",required))
        if not re.search(affirmative, condition_text) and not (known_pair and _district_student_scope(condition_text)):
            return "global_scope"
    # Recognize only explicit fee-exemption clauses, requiring the source's
    # qualification in any numeric payment item rather than an undefined group.
    if _FEE_CUE.search(item.text) and _numeric_literals(item.text):
        for exemption in re.findall(r"([^;।\n]+?দের\s+ফি\s+দিতে\s+হবে\s+না)", source_text):
            if normalize_whitespace(exemption) not in condition_text and not _disability_fee_exception(condition_text,exemption):
                return "fee_exception"
    # Bounded default/first-correction fee pattern observed in alpha acceptance.
    # A separate alternative must qualify a standalone default amount too.
    if _FEE_CUE.search(item.text) and _numeric_literals(item.text):
        default = re.search(r"সাধারণ\s+ফি\s+([০-৯0-9]+)\s+টাকা", source_text)
        alternatives = re.findall(r"প্রথমবার[^;।\n]*জন্মতারিখ[^;।\n]*ফি\s+[০-৯0-9]+\s+টাকা[।]?", source_text)
        if default and _numeric_literals(default.group(1)) <= _numeric_literals(item.text):
            if any(_quotation_key(clause).rstrip("।") not in _quotation_key(condition_text).rstrip("।") for clause in alternatives):
                return "fee_exception"
    # A condition about a previously submitted certificate cannot qualify the
    # explicitly independent form rule. Never repair that attachment automatically.
    if ("ফি না লাগলেও আবেদনপত্র জমা দিতে হবে" in normalize_whitespace(source_text)
            and "আবেদনপত্র" in item.text and "জমা" in item.text
            and re.search(r"আগে.{0,25}সনদ|সনদ.{0,25}আগে|previous.{0,30}certificate", condition_text, re.I)):
        return "local_condition_leak"
    if ("ফি না লাগলেও আবেদনপত্র জমা দিতে হবে" in normalize_whitespace(source_text)
            and re.search(r"আবেদনপত্র|\bform\b", item.text, re.I)
            and re.search(r"জমা.{0,20}(?:হবে না|দেবেন না|দিবেন না|করবেন না|প্রয়োজন নেই|প্রয়োজন নেই)|need not submit|not required to submit|do not need to submit|do not submit|don't submit", item.text, re.I)):
        return "form_submission_negation"
    # Bounded extractive certificate-alternative contract. It only withholds;
    # unrecognized phrasing is not a semantic proof and remains a validation limit.
    for alternative in re.finditer(r"([\u0980-\u09FF]+\s+সনদ\s+অথবা\s+[\u0980-\u09FF]+\s+প্রত্য[য়য়]নপত্র)", source_text):
        if "সনদ" in item.text and (section == "documents" or _REQUIREMENT_CUE.search(item.text)):
            if normalize_whitespace(alternative.group()) not in normalize_whitespace(item.text):
                return "document_alternative"
            if re.search(r"দুটোই\s+লাগবে(?!\s+না)", item.text):
                return "document_alternative"
            prior = re.search(r"(আগে\s+সনদ\s+জমা\s+না\s+দিয়ে\s+থাকলে)", source_text)
            if prior and not _prior_certificate_exception(condition_text):
                return "prior_submission"
    return None


def _uncovered_form_rule(source_text, visible_claims):
    """Flag the observed coverage gap, not prove general completeness or repair text."""
    rule = re.search(r"(?:^|(?<=[।\n]))\s*(ফি\s+না\s+লাগলেও\s+আবেদনপত্র\s+জমা\s+দিতে\s+হবে[ \t]*।)", source_text)
    if not rule:
        return None
    for claim in visible_claims:
        if claim.semantic_status != "supported":
            continue
        text = normalize_whitespace(claim.text)
        for scope in _GLOBAL_PAIR.finditer(source_text):
            phrase = re.escape(normalize_whitespace(scope.group(1)) + " হলে")
            text = re.sub(r"(?:শুধু\s+)?" + phrase + r"(?=\s|[,।:]|$)", "", text)
        # An explicit general form action can cover this narrow source rule.
        # A further subgroup/prior-submission condition cannot replace it.
        if (re.search(r"আবেদনপত্র\s+জমা\s+(?:দিন|দিতে হবে)(?=\s|[।,;:]|$)(?!\s+না)", text)
                and not re.search(r"হলে|ক্ষেত্রে|শুধু|কেবল|যদি|\b(?:if|unless|only)\b", text, re.I)):
            return None
    return rule.group(1)


def deterministic_requirement_reason(item, section, source_text, original_quotes, *, shared_conditions=()):
    """One deterministic requirement gate shared by reviewed and degraded paths."""
    negative_pattern = (
        r"(?:জমা|দাখিল|প্রদর্শন).{0,35}(?:হবে না|প্রয়োজন নেই|প্রয়োজন নেই)|"
        r"(?:do not|not required|need not).{0,35}(?:submit|present|copy|document)")
    negative_submission = False
    if _document_request(item.text, section):
        # Resolve each local clause rather than importing negation from a whole
        # supporting paragraph into every document/alternative in that paragraph.
        clauses = re.split(r"(?<=[।.!?;])\s+|\n+", original_quotes)
        def entities(text):
            return _document_entities(text) | set(re.findall(
                r"\b(?:card|letter|form|certificate|passport|badge|pass|originals?)\b|সনদ|আবেদনপত্র|কার্ড|চিঠি", text.casefold()))
        requested = entities(item.text)
        for clause in clauses:
            if not re.search(negative_pattern, clause, re.I):
                continue
            if re.search(negative_pattern, item.text, re.I) and _quote_found(item.text, clause):
                continue  # Faithful source prohibition, not an affirmative demand.
            negated = entities(clause)
            if requested and negated and not requested.intersection(negated):
                continue
            conditional = re.search(r"previous|already|unless|if\b|আগে|ইতোমধ্যে|ক্ষেত্রে|যদি", clause, re.I)
            attached = any(_quote_found(clause, c) and _quote_found(c, source_text) for c in item.source_conditions)
            if conditional and attached:
                continue  # The exact exemption remains visibly attached.
            negative_submission = True
            break
    absence_source = re.search(r"দেওয়া নেই|দেওয়া নেই|not stated|not specified|not provided",original_quotes,re.I)
    invented_absence = re.search(r"সময়সীমা নেই|সময়সীমা নেই|বিনামূল্যে|unlimited|no deadline|\bfree\b",item.text,re.I)
    if _document_request(item.text,section) and negative_submission:
        return "document_negation"
    if section == "documents" and _information_only(item.text):
        return "information_not_document"
    if absence_source and invented_absence:
        return "invented_absence"
    return scope_withholding_reason(item,section,source_text,original_quotes,shared_conditions=shared_conditions)


def apply_semantic_review(result: AnalysisResult, source_text: str, review: SemanticReview,
                          *, output_language: Language = "bn") -> AnalysisResult:
    """Claim-level withholding; never repair text or override failed literal checks."""
    candidates = review_candidates(result)
    if len(review.decisions) > 120 or len(review.evidence) > 120:
        raise AnalysisError("malformed_response", "Semantic review exceeds the supported bound.")
    decisions = {d.claim_id: d for d in review.decisions}
    if len(decisions) != len(review.decisions) or set(decisions) != set(candidates):
        raise AnalysisError("malformed_response", "Semantic review did not cover every claim exactly once.")
    ids = [e.id for e in review.evidence]
    if len(ids) != len(set(ids)):
        raise AnalysisError("malformed_response", "Duplicate review evidence IDs.")
    quoted = {e.id: _original_excerpt(e.excerpt, source_text) for e in review.evidence
              if _quote_found(e.excerpt, source_text)}
    # Review IDs are a separate namespace. Only matching source text gains an
    # application-owned reference; the model cannot promote provenance/status.
    evidence = [e.model_copy(deep=True) for e in result.evidence]
    next_id = max((int(e.id[1:]) for e in evidence), default=0) + 1
    refs = {}
    for key, text in quoted.items():
        existing = next((e.id for e in evidence if e.excerpt_found and e.excerpt == text), None)
        if existing is None:
            existing = f"e{next_id}"; next_id += 1
            evidence.append(CheckedEvidence(id=existing, excerpt=text, excerpt_found=True))
        refs[key] = existing
    sections = {name: [] for name in ("explanation", "steps", "documents", "fees", "deadlines")}
    unknowns = []; uncited_time_absence = []
    withheld_refs = []; conflict_refs = []; withheld = False; conflict = False
    document_scope_held = False; fee_details_uncertain = False
    notices = NOTICES[output_language]
    warning_prefixes = [notices["claim_warning"].format(status=notices[status], claim="")
                        for status in ("unsupported", "contradictory")]
    all_review_ids = set(ids)
    global_clauses = [m.group() for pattern in (_GLOBAL_PAIR, _ENGLISH_ELIGIBILITY)
                      for m in pattern.finditer(source_text)]
    def global_condition(text):
        return any(_quotation_key(text) == _quotation_key(clause) for clause in global_clauses)
    def own_global_context(item):
        return [c for c in getattr(item, "source_conditions", [])
                if global_condition(c) and _quote_found(c, source_text)]
    shared = []
    for candidate_id, candidate in candidates.items():
        section = candidate_id.split(":")[0]
        decision = decisions[candidate_id]
        if section not in ("explanation", "fees", "deadlines"):
            continue
        if (decision.section != section or candidate.evidence_status != "quotation_matched" or not decision.evidence_ids
                or decision.verdict not in ("supported", "uncertain")
                or any(ref not in quoted for ref in decision.evidence_ids + decision.missing_condition_ids)):
            continue
        # A peer may itself be scoped by its literal attached global clause.
        own = own_global_context(candidate)
        if decision.missing_condition_ids and not all(global_condition(quoted[ref]) and
                any(_quotation_key(quoted[ref]) == _quotation_key(c) for c in own)
                for ref in decision.missing_condition_ids):
            continue
        if decision.verdict == "uncertain" and not decision.missing_condition_ids:
            continue
        quotes = " ".join(e.excerpt for e in result.evidence if e.excerpt_found and e.id in candidate.evidence_ids)
        if deterministic_requirement_reason(candidate, section, source_text, quotes,
                shared_conditions=[c for c in shared if global_condition(c)]):
            continue
        if section == "explanation":
            shared.extend(c for c in global_clauses if _quote_found(c, candidate.text + " " + " ".join(own)))
        else:
            shared.extend(quoted[ref] for ref in decision.evidence_ids)
    for key, item in candidates.items():
        decision = decisions[key]
        section = key.split(":")[0]
        cited = decision.evidence_ids + decision.missing_condition_ids
        if any(ref not in all_review_ids for ref in cited):
            raise AnalysisError("malformed_response", "Unknown semantic review evidence ID.")
        literal_review = all(ref in quoted for ref in cited)
        mapped_refs = [refs[ref] for ref in cited if ref in refs]
        correct_section = decision.section == section or (
            section == "explanation" and decision.section in ("fees", "deadlines"))
        coverage = shared + own_global_context(item)
        def covered(ref):
            if ref not in quoted:
                return False
            clause = quoted[ref]
            global_scope = global_condition(clause)
            # Do not let a broad review quote turn a local exception into shared context.
            one_clause = len(re.findall(r"[.!?।]", clause.rstrip(".!?। "))) == 0
            shared_fact = (section in ("steps", "documents") and one_clause and
                not re.search(r"certificate|document|সনদ|কাগজ", clause, re.I) and
                bool(_FEE_CUE.search(clause) or re.search(r"\b(?:deadline|apply by|submit by)\b|সময়সীমা|সময়সীমা|তারিখ|এর মধ্যে|\d{4}", clause, re.I)))
            return (global_scope or shared_fact) and any(_quote_found(clause, passage) for passage in coverage)
        missing = [ref for ref in decision.missing_condition_ids if not covered(ref)]
        context_only_hold = (section != "unknowns" and decision.verdict == "uncertain" and bool(decision.missing_condition_ids) and not missing)
        accepted = ((decision.verdict == "supported" or context_only_hold) and not missing
                    and literal_review and correct_section)
        if section == "unknowns":
            # A whole-category absence notice without source evidence cannot
            # stand alongside explicit fee cues. This only withholds a notice;
            # it never infers an amount, exemption or a fee requirement.
            if (item.kind == "missing" and not item.evidence_ids and
                    _missing_notice_category(item.text) == "ফি" and _FEE_CUE.search(source_text)):
                accepted = False
                fee_details_uncertain = True
            # Do not echo an unsafe generated claim inside a post-processor warning.
            accepted = accepted and not any(item.text.startswith(prefix) for prefix in warning_prefixes)
            accepted = accepted and (bool(decision.evidence_ids) or item.kind == "missing")
            accepted = accepted and all(any(e.id == ref and e.excerpt_found for e in result.evidence)
                                        for ref in item.evidence_ids)
            if accepted:
                # Track original absence citations before attaching review refs.
                destination = uncited_time_absence if (item.kind == "missing" and not item.evidence_ids
                    and _missing_notice_category(item.text) == "সময়সীমা") else unknowns
                destination.append(item.model_copy(update={"evidence_ids": list(dict.fromkeys(item.evidence_ids + mapped_refs))}))
        else:
            accepted = accepted and item.evidence_status == "quotation_matched" and bool(decision.evidence_ids)
            target = decision.section
            if (accepted and section == "explanation" and _FEE_CUE.search(item.text)
                    and not re.search(r"আবেদনপত্র|\bform\b", item.text, re.I)):
                # Reclassify unchanged, already reviewed fee information; never
                # infer missing amounts or modify the stated conditions.
                target = "fees"
            original_quotes = " ".join(e.excerpt for e in result.evidence
                                       if e.excerpt_found and e.id in item.evidence_ids)
            if (accepted and section == "explanation"
                    and _PASSPORT_DELIVERY.fullmatch(_quotation_key(item.text))
                    and any(e.excerpt_found and e.id in item.evidence_ids
                            and _quotation_key(item.text) in _quotation_key(e.excerpt) for e in result.evidence)):
                target = "deadlines"  # Unchanged delivery timeframe, including every source condition.
            scope_reason = deterministic_requirement_reason(item,target,source_text,original_quotes,
                shared_conditions=[c for c in shared if global_condition(c)]) if accepted else None
            if scope_reason:
                accepted = False
                document_scope_held = document_scope_held or scope_reason == "document_scope"
            if accepted and target in ("steps", "documents", "fees", "deadlines"):
                for global_rule in list(_GLOBAL_PAIR.finditer(source_text))+list(_ENGLISH_ELIGIBILITY.finditer(source_text)):
                    source_rule = global_rule.group()
                    global_ref = next((e.id for e in evidence if e.excerpt_found and source_rule in e.excerpt), None)
                    if global_ref is None:
                        global_ref = f"e{next_id}"; next_id += 1
                        evidence.append(CheckedEvidence(id=global_ref, excerpt=source_rule, excerpt_found=True))
                    mapped_refs.append(global_ref)
            claim = item.model_copy(update={"semantic_status": "supported" if accepted else "withheld",
                "scope_hold_code":scope_reason,"review_verdict":decision.verdict,
                "review_missing_conditions":bool(missing),
                "evidence_ids": list(dict.fromkeys(item.evidence_ids + mapped_refs)),
                "withholding_reason":None if accepted else item.withholding_reason or ("missing_conditions" if scope_reason in {"global_scope","fee_exception","document_alternative","prior_submission"} or missing else "unresolved_scope" if scope_reason else "unsupported_interpretation")})
            sections[target if accepted else section].append(claim)
        if not accepted:
            if section == "unknowns":
                unknowns.append(Uncertainty(kind="unverified", category=item.category,
                    reason_code="missing_conditions" if decision.missing_condition_ids else "unsupported_interpretation",
                    text=notices["semantic_withheld"], evidence_ids=list(dict.fromkeys(mapped_refs))))
            withheld = True
            withheld_refs.extend(mapped_refs)
            # Candidate/source disagreement is withholding, not a source conflict.
    # Routing can fill a category after the literal-check stage. Remove only its
    # uncited whole-category boilerplate; keep cited/conflicting/partial absence
    # notices (a delivery timeframe does not establish an application cutoff).
    if not any(c.semantic_status == "supported" for c in sections["deadlines"]):
        unknowns.extend(uncited_time_absence)
    if withheld:
        unknowns.append(Uncertainty(kind="unverified", text=notices["semantic_withheld"],
                                   evidence_ids=list(dict.fromkeys(withheld_refs))))
    if conflict:
        unknowns.append(Uncertainty(kind="contradiction", text=notices["semantic_conflict"],
                                   evidence_ids=list(dict.fromkeys(conflict_refs))))
    if document_scope_held:
        unknowns.append(Uncertainty(kind="unverified", text=notices["semantic_document_scope"],
                                   evidence_ids=list(dict.fromkeys(withheld_refs))))
    if fee_details_uncertain:
        unknowns.append(Uncertainty(kind="unverified", text=notices["semantic_fee_details"], evidence_ids=[]))
    form_rule = _uncovered_form_rule(source_text, [c for items in sections.values() for c in items])
    if form_rule:
        # Original excerpts only: no generated replacement action or authority claim.
        passages = [form_rule] + [m.group() for m in _GLOBAL_PAIR.finditer(source_text)]
        form_refs = []
        for passage in passages:
            ref = next((e.id for e in evidence if e.excerpt_found and passage in e.excerpt), None)
            if ref is None:
                ref = f"e{next_id}"; next_id += 1
                evidence.append(CheckedEvidence(id=ref, excerpt=passage, excerpt_found=True))
            form_refs.append(ref)
        unknowns.append(Uncertainty(kind="unverified", text=notices["semantic_form_coverage"],
                                   evidence_ids=list(dict.fromkeys(form_refs))))
    return result.model_copy(update={"explanation": sections["explanation"], "steps": sections["steps"],
        "documents": sections["documents"],
        "fees_and_deadlines": CheckedFeesAndDeadlines(fees=sections["fees"], deadlines=sections["deadlines"]),
        "unknowns": unknowns, "evidence": evidence, "semantic_review_complete": True})


def review_semantics(result, source_text, *, settings, session=None, question=None,
                     source_scope=None, output_language="bn"):
    """One separate, bounded semantic review; never retry or repair generated text."""
    report_progress("verifying")
    message = build_review_message(result, source_text, question=question, source_scope=source_scope)
    tokens = len((message + SEMANTIC_REVIEW_PROMPT + json.dumps(SemanticReview.model_json_schema())).encode("utf-8")) + 2048
    # Keep the complete source and strict schema. Give the independent review
    # a bounded 90s deadline; never truncate its evidence to save latency.
    response = gemini_generate(settings, contents=message, tokens=tokens, stage="semantic_review",
            timeout_ms=90_000, session=session,
            config=types.GenerateContentConfig(system_instruction=SEMANTIC_REVIEW_PROMPT,
                response_mime_type="application/json", response_json_schema=strip_grammar_bounds(SemanticReview.model_json_schema()),
                temperature=0, max_output_tokens=8192))
    if not response.candidates or any(c.finish_reason != types.FinishReason.STOP for c in response.candidates):
        raise AnalysisError("malformed_response", "Semantic review did not finish.")
    review = SemanticReview.model_validate_json(response.text or "")
    record_trace("semantic_review_validated",output=review.model_dump())
    checked = apply_semantic_review(result, source_text, review, output_language=output_language)
    return add_coverage_gaps(checked, source_text, review.omissions, output_language)


def add_coverage_gaps(result, source_text, gaps, language):
    """Expose original omitted passages as uncertainty, never as admitted facts."""
    evidence, unknowns = list(result.evidence), list(result.unknowns)
    for gap in gaps:
        if not _quote_found(gap.source_quote, source_text):
            record_trace("coverage_gap_skipped", reason="quotation_mismatch")
            continue
        quote = _original_excerpt(gap.source_quote, source_text)
        existing = next((e for e in evidence if _quotation_key(e.excerpt) == _quotation_key(quote)), None)
        ref = existing.id if existing else f"e{max([int(e.id[1:]) for e in evidence] or [0])+1}"
        if existing is None:
            evidence.append(CheckedEvidence(id=ref, excerpt=quote, excerpt_found=True))
        text = ("উৎসের এই অংশটি পরিকল্পনায় পুরোপুরি রাখা যায়নি; মূল লেখাটি দেখে নিন।" if language == "bn" else
                "This source passage could not be fully represented in the plan; check the original wording.")
        unknowns.append(Uncertainty(category=gap.category, kind="unverified", reason_code="unsupported_interpretation",
                                   text=text, evidence_ids=[ref]))
    return result.model_copy(update={"evidence": evidence, "unknowns": unknowns})


def raise_provider_error(error, *, model):
    """Shared fixed-code errors for extraction and analysis; never expose raw errors."""
    diagnostics = provider_diagnostics(error, model=model)
    if error.code in (500, 502, 503):
        raise AnalysisError("service_busy", "AI সেবাটি এখন ব্যস্ত বা সাময়িকভাবে পাওয়া যাচ্ছে না। কিছুক্ষণ পরে আবার চেষ্টা করুন।", diagnostics=diagnostics) from None
    if error.code == 429:
        raise AnalysisError("rate_limit_or_quota", "AI সেবার অনুরোধের সীমা বা কোটা শেষ হয়েছে। অনুরোধটি আবার পাঠানো হয়নি। প্রস্তুত উদাহরণটি দেখুন। পরে চেষ্টা করার আগে AI Studio-তে মডেলের কোটা দেখে নিন।", diagnostics=diagnostics) from None
    if error.code in (401, 403):
        raise AnalysisError("access_denied", "AI সেবাটি ব্যবহারের অনুমতি পাওয়া যায়নি। API key ও মডেল ব্যবহারের অনুমতি দেখে নিন।", diagnostics=diagnostics) from None
    if error.code == 404:
        raise AnalysisError("model_unavailable", "বেছে নেওয়া AI মডেলটি পাওয়া যায়নি। GEMINI_MODEL ঠিক আছে কি না এবং মডেলটি আপনার অ্যাকাউন্টে ব্যবহার করা যায় কি না দেখে নিন।", diagnostics=diagnostics) from None
    if error.code in (408, 504):
        raise AnalysisError("timeout", "নির্ধারিত সময়ের মধ্যে AI সেবার উত্তর পাওয়া যায়নি। পরে আবার চেষ্টা করুন।", diagnostics=diagnostics) from None
    raise AnalysisError("provider_error", "AI সেবায় সমস্যা হয়েছে। পরে আবার চেষ্টা করুন।", diagnostics=diagnostics) from None


def analysis_enabled() -> bool:
    return ANALYSIS_ENABLED


def _analyze_gemini(
    instruction_text: str,
    *,
    source_type: SourceType = "user_provided",
    source_url: str | None = None,
    output_language: Language = "bn",
    session: SessionSubmission | None = None,
    question: str | None = None,
    source_scope: str | None = None,
    settings_override: Settings | None = None,
) -> AnalysisResult:
    """One generation and a separate review, with labelled local-check recovery."""
    report_progress("analyzing")
    if output_language not in LANGUAGES:
        raise AnalysisError("invalid_input", "Unsupported output language")
    if not isinstance(instruction_text, str) or not instruction_text.strip():
        raise AnalysisError("invalid_input", "নির্দেশনার লেখা পেস্ট করুন।")
    if len(instruction_text) > MAX_CHARACTERS:
        raise AnalysisError("invalid_input", "লেখা ৫০,০০০ অক্ষরের বেশি হয়েছে।")
    # Curated examples are loaded separately from reviewed static files, never
    # generated by this endpoint. Pasted text cannot promote itself to official.
    if source_type != "user_provided" or source_url is not None:
        raise AnalysisError("source_provenance", "এই সংস্করণে শুধু আপনার দেওয়া লেখা বিশ্লেষণ করা যায়। লেখাটি সরকারি উৎসের সঙ্গে আলাদাভাবে মিলিয়ে দেখা হয় না।")
    if question is not None and (not isinstance(question, str) or len(question) > 500):
        raise AnalysisError("invalid_input", "Question exceeds the supported limit")
    if source_scope is not None and (not isinstance(source_scope, str) or len(source_scope) > 1000):
        raise AnalysisError("invalid_input", "Source scope exceeds the supported limit")
    if not analysis_enabled():
        raise AnalysisError("analysis_paused", "AI analysis is temporarily paused pending P1 acceptance.")
    settings = settings_override or load_settings()
    try:
        source_message = build_source_message(instruction_text, question, source_scope)
        inventory = None
        if len(instruction_text) > 10_000:
            from source_inventory import extract_inventory
            try:
                inventory = extract_inventory(instruction_text, settings=settings, language=output_language, session=session)
            except Exception as error:
                # Inventory is an aid. The complete source still reaches both
                # generation and review; their deadline/budget guards still run.
                record_trace("source_inventory_unavailable", error_type=type(error).__name__)
            packet = json.loads(source_message)
            packet["material_inventory"] = inventory
            source_message = json.dumps(packet, ensure_ascii=False)
        response = gemini_generate(settings, contents=source_message, stage="source_generation", session=session,
                tokens=estimate_input_tokens(source_message, output_language),
                config=types.GenerateContentConfig(
                    system_instruction=build_system_prompt(output_language),
                    response_mime_type="application/json",
                    # Use JSON Schema directly. The SDK's legacy response_schema
                    # conversion emits unsupported additional_properties fields
                    # for Pydantic extra='forbid', causing API INVALID_ARGUMENT.
                    response_json_schema=strip_grammar_bounds(QuoteFirstAnalysis.model_json_schema()),
                    temperature=0,
                    max_output_tokens=8192,
                ),
            )
        # Reject truncation, blocked content, or other incomplete candidate output.
        if not response.candidates or any(
            candidate.finish_reason != types.FinishReason.STOP for candidate in response.candidates
        ):
            raise AnalysisError("malformed_response", "AI সম্পূর্ণ উত্তর দিতে পারেনি বা উত্তরটি আটকে গেছে। আবার চেষ্টা করুন।")
        parsed = adapt_quote_first(QuoteFirstAnalysis.model_validate_json(response.text or ""),instruction_text)
        record_trace("source_candidates",output=parsed.model_dump())
        checked = check_evidence(parsed, instruction_text, source_type=source_type, source_url=None,
                                 model=settings.model, output_language=output_language)
        record_trace("deterministic_checks",output=checked.model_dump())
        try:
            reviewed = review_semantics(checked, instruction_text, settings=settings, session=session,
                                       question=question, source_scope=source_scope, output_language=output_language)
            if inventory is not None:
                from source_inventory import uncovered_facts
                reviewed = add_coverage_gaps(reviewed, instruction_text, uncovered_facts(inventory, reviewed), output_language)
            return reviewed
        except (errors.APIError,httpx.TimeoutException,TimeoutError,AnalysisError,ValidationError,ValueError) as error:
            degraded=deterministic_review_fallback(checked,error,source_text=instruction_text)
            if degraded is not None:
                if inventory is not None:
                    from source_inventory import uncovered_facts
                    degraded = add_coverage_gaps(degraded, instruction_text, uncovered_facts(inventory, degraded), output_language)
                return degraded
            raise
    except AnalysisError:
        raise
    except BudgetExceeded as error:
        raise AnalysisError(error.code, str(error)) from None
    except (httpx.TimeoutException, TimeoutError):
        raise AnalysisError("timeout", "নির্ধারিত সময়ের মধ্যে AI সেবার উত্তর পাওয়া যায়নি। কিছুক্ষণ পরে আবার চেষ্টা করুন।") from None
    except httpx.TransportError:
        raise AnalysisError("network_error", "AI সেবার সঙ্গে সংযোগ করা যায়নি। কিছুক্ষণ পরে আবার চেষ্টা করুন।") from None
    except errors.APIError as error:
        raise_provider_error(error, model=settings.model)
    except (ValidationError, ValueError):
        raise AnalysisError("malformed_response", "AI উত্তরের বিন্যাস সঠিক নয়। ফলাফল দেখানো যায়নি। আবার চেষ্টা করুন।") from None
    except Exception:
        # No exception strings/tracebacks: they may contain the key or source text.
        raise AnalysisError("unexpected", "বিশ্লেষণ শেষ করা যায়নি। পরে আবার চেষ্টা করুন।") from None


def _openrouter_key() -> SecretStr | None:
    """An explicit server-only environment key opts into the bounded fallback."""
    if not (OPENROUTER_FALLBACK_ENABLED or os.environ.get("OPENROUTER_API_KEY")):
        return None
    try:
        key = os.environ.get("OPENROUTER_API_KEY")
    except FileNotFoundError:
        return None
    except Exception:
        raise AnalysisError("configuration", "Optional provider configuration could not be read") from None
    if key is None or isinstance(key, str) and (not key.strip() or key.strip() in {
        "replace-with-your-own-key-locally", "your-own-key-here", "your-own-key"}):
        return None
    if not isinstance(key, str):
        raise AnalysisError("configuration", "Optional provider credential must be text")
    return SecretStr(key.strip())


def _fallback_eligible(error: AnalysisError) -> bool:
    if error.quota_pool_exhausted:
        return False
    if error.code in {"service_busy", "rate_limit_or_quota", "timeout", "network_error"}:
        return True
    return (error.code == "provider_error" and error.diagnostics is not None
            and 500 <= error.diagnostics.http_status <= 599)


def _analyze_openrouter(instruction_text, *, api_key, output_language, session,
                        question, source_scope, provider="openrouter", model=None):
    """One fresh generation/review pair with unchanged evidence and scope checks."""
    report_progress("analyzing")
    model = model or os.environ.get("OPENROUTER_MODEL",openrouter_service.OPENROUTER_MODEL)
    scope = (hashlib.sha256(api_key.get_secret_value().encode()).hexdigest(), model)

    def request(system_prompt, message, response_type, tokens):
        delay = REQUEST_BUDGET.wait_seconds(scope)
        if delay:
            sleep(delay)
        REQUEST_BUDGET.reserve(scope, tokens, session=session)
        raw = openrouter_service.generate_json(api_key=api_key, system_prompt=system_prompt,
            message=message, schema=response_type.model_json_schema(),model=model,provider=provider)
        return response_type.model_validate_json(raw)

    try:
        source_message = build_source_message(instruction_text, question, source_scope)
        parsed = request(build_system_prompt(output_language), source_message, QuoteFirstAnalysis,
                         estimate_input_tokens(source_message, output_language))
        parsed = adapt_quote_first(parsed,instruction_text)
        checked = check_evidence(parsed, instruction_text, source_type="user_provided",
                                 source_url=None, model=model, output_language=output_language)
        message = build_review_message(checked, instruction_text, question=question, source_scope=source_scope)
        report_progress("verifying")
        tokens = len((message + SEMANTIC_REVIEW_PROMPT + json.dumps(SemanticReview.model_json_schema())).encode("utf-8")) + 2048
        try:
            review = request(SEMANTIC_REVIEW_PROMPT, message, SemanticReview, tokens)
            checked_review = apply_semantic_review(checked, instruction_text, review, output_language=output_language)
            return add_coverage_gaps(checked_review, instruction_text, review.omissions, output_language)
        except (openrouter_service.OpenRouterError,errors.APIError,httpx.TimeoutException,TimeoutError,AnalysisError,ValidationError,ValueError) as error:
            degraded=deterministic_review_fallback(checked,error,source_text=instruction_text)
            if degraded is not None:
                return degraded
            raise
    except AnalysisError:
        raise
    except BudgetExceeded as error:
        raise AnalysisError(error.code, str(error)) from None
    except openrouter_service.OpenRouterError as error:
        raise AnalysisError(error.code, "Optional OpenRouter analysis failed; no further attempt was sent") from None
    except (ValidationError, ValueError):
        raise AnalysisError("malformed_response", "Optional provider response did not pass validation") from None
    except Exception:
        raise AnalysisError("unexpected", "Optional provider analysis could not finish") from None


def analyze_instructions(
    instruction_text: str, *, source_type: SourceType = "user_provided",
    source_url: str | None = None, output_language: Language = "bn",
    session: SessionSubmission | None = None, question: str | None = None,
    source_scope: str | None = None,
) -> AnalysisResult:
    """Gemini first; at most one configured secondary pair after a service failure.

    Primary validates inputs and the emergency switch before any request. Schema,
    semantic, local admission and configuration rejections never trigger routing.
    Failed reviews retain locally admitted claims with explicit degraded metadata.
    """
    try:
        return _analyze_gemini(instruction_text, source_type=source_type, source_url=source_url,
            output_language=output_language, session=session, question=question, source_scope=source_scope)
    except AnalysisError as error:
        if not _fallback_eligible(error):
            raise
        alternate=os.environ.get("GEMINI_FALLBACK_MODEL","").strip()
        if alternate and alternate!=os.environ.get("GEMINI_MODEL",DEFAULT_MODEL):
            settings=load_settings().model_copy(update={"model":alternate})
            return _analyze_gemini(instruction_text,source_type=source_type,source_url=source_url,
                output_language=output_language,session=session,question=question,source_scope=source_scope,settings_override=settings)
        api_key = _openrouter_key()
        if api_key is None:
            groq=os.environ.get("GROQ_API_KEY","").strip()
            if groq:
                return _analyze_openrouter(instruction_text,api_key=SecretStr(groq),output_language=output_language,
                    session=session,question=question,source_scope=source_scope,provider="groq",
                    model=os.environ.get("GROQ_MODEL","openai/gpt-oss-120b"))
            raise
        return _analyze_openrouter(instruction_text, api_key=api_key, output_language=output_language,
            session=session, question=question, source_scope=source_scope)

def deterministic_review_fallback(result,error,*,source_text: str):
    """Expose only locally admitted claims, with an app-owned degraded marker."""
    if not deterministic_review_enabled():
        return None
    code=getattr(error,"code",None)
    if code==429:
        code="rate_limit_or_quota"
    # Google API deadline errors reach this boundary before raise_provider_error.
    # Never infer timeouts from arbitrary exception text (which may contain input).
    if isinstance(error, errors.APIError) and (code in {408, 504}
            or getattr(error, "status", None) == "DEADLINE_EXCEEDED"):
        code="timeout"
    if isinstance(error,(httpx.TimeoutException,TimeoutError)):
        code="timeout"
    if isinstance(error, errors.APIError) and code not in {"timeout", "rate_limit_or_quota"}:
        code = "service_busy" if code in {500, 502, 503} else "provider_error"
    if isinstance(error, (ValidationError, ValueError)):
        code = "malformed_response"
    if not isinstance(code, str) or not code:
        code = "review_failed"
    record_trace("semantic_review_degraded", reason=code)
    shared_global=[]
    for pattern in (_GLOBAL_PAIR,_ENGLISH_ELIGIBILITY):
        for rule in pattern.finditer(source_text):
            for overview in result.explanation:
                if (overview.evidence_status=="quotation_matched" and
                        _quote_found(rule.group(),overview.text+" "+" ".join(overview.source_conditions))):
                    quotes=" ".join(e.excerpt for e in result.evidence if e.excerpt_found and e.id in overview.evidence_ids)
                    if not deterministic_requirement_reason(overview,"explanation",source_text,quotes):
                        shared_global.append(rule.group())
                        break
    sections={}
    for section,items in {"explanation":result.explanation,"steps":result.steps,"documents":result.documents,
            "fees":result.fees_and_deadlines.fees,"deadlines":result.fees_and_deadlines.deadlines}.items():
        checked=[]
        for item in items:
            quotes=" ".join(e.excerpt for e in result.evidence if e.excerpt_found and e.id in item.evidence_ids)
            reason=deterministic_requirement_reason(item,section,source_text,quotes,shared_conditions=shared_global) if item.evidence_status=="quotation_matched" else None
            if reason:
                item=item.model_copy(update={"semantic_status":"withheld","scope_hold_code":reason,
                    "withholding_reason":"missing_conditions" if reason in {"global_scope","fee_exception","document_alternative","prior_submission"} else "unresolved_scope"})
            checked.append(item)
        sections[section]=checked
    result=result.model_copy(update={"explanation":sections["explanation"],"steps":sections["steps"],"documents":sections["documents"],
        "fees_and_deadlines":CheckedFeesAndDeadlines(fees=sections["fees"],deadlines=sections["deadlines"])})
    return result.model_copy(update={"review_mode":"deterministic_only","review_failure":code,
        "semantic_review_complete":False})



def analyze_ask(question: str, *, output_language: Language = "bn",
                session: SessionSubmission | None = None) -> GeneralAskResult:
    """One structured Gemini request. No substring gate, review or fallback."""
    if (output_language not in LANGUAGES or not isinstance(question, str)
            or not question.strip() or len(question) > 2000):
        raise AnalysisError("invalid_input", "Enter a goal of at most 2,000 characters.")
    if not analysis_enabled():
        raise AnalysisError("analysis_paused", "Analysis is temporarily unavailable.")
    settings = load_settings()
    report_progress("analyzing")
    try:
        message = json.dumps({"goal": question}, ensure_ascii=False)
        response = gemini_generate(settings, contents=message, stage="general_ask", session=session,
                tokens=estimate_input_tokens(message, output_language),
                config=types.GenerateContentConfig(system_instruction=build_ask_prompt(output_language),
                    response_mime_type="application/json", response_json_schema=strip_grammar_bounds(AskPlan.model_json_schema()),
                    temperature=0, max_output_tokens=4096))
        if not response.candidates or any(c.finish_reason != types.FinishReason.STOP for c in response.candidates):
            raise AnalysisError("malformed_response", "The action plan was incomplete.")
        plan = AskPlan.model_validate_json(response.text or "")
        record_trace("ask_schema_validated",output=plan.model_dump())
        return GeneralAskResult(**plan.model_dump(), output_language=output_language)
    except AnalysisError:
        raise
    except BudgetExceeded as error:
        raise AnalysisError(error.code, str(error)) from None
    except (httpx.TimeoutException, TimeoutError):
        raise AnalysisError("timeout", "The planning request timed out.") from None
    except httpx.TransportError:
        raise AnalysisError("network_error", "The planning service could not be reached.") from None
    except errors.APIError as error:
        raise_provider_error(error, model=settings.model)
    except (ValidationError, ValueError):
        raise AnalysisError("malformed_response", "The action plan could not be read.") from None
    except Exception:
        raise AnalysisError("unexpected", "The action plan could not be completed.") from None

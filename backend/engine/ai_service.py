def provider_diagnostics(error: errors.APIError, *, model: str) -> ProviderDiagnostics:
    """Keep actionable, recognized diagnostics without echoing private input.

    General redaction cannot safely remove arbitrary fragments of source text
    echoed by a provider. Retain only recognized public schema-error templates;
    other messages become fixed summaries. Do not persist error.details itself.
    """
    statuses = {
        "INVALID_ARGUMENT", "FAILED_PRECONDITION", "PERMISSION_DENIED",
        "UNAUTHENTICATED", "NOT_FOUND", "RESOURCE_EXHAUSTED", "INTERNAL",
        "UNAVAILABLE", "DEADLINE_EXCEEDED", "ABORTED", "CANCELLED",
        "OUT_OF_RANGE", "DATA_LOSS", "UNKNOWN", "ALREADY_EXISTS",
    }
    status = error.status if isinstance(error.status, str) and error.status in statuses else "UNKNOWN"
    raw_message = error.message if isinstance(error.message, str) else ""
    safe_fields = {
        "additional_properties", "additionalProperties", "response_schema",
        "response_json_schema", "responseSchema", "responseJsonSchema",
        "temperature", "max_output_tokens", "maxOutputTokens", "system_instruction",
    }
    safe_path_parts = {
        "generation_config", "generationConfig", "response_schema", "responseSchema",
        "response_json_schema", "responseJsonSchema", "properties", "value", "items",
    }
    recognized = []
    pattern = r'''Invalid JSON payload received\. Unknown name "([A-Za-z_][A-Za-z_0-9]*)" at '([A-Za-z_0-9.\[\]]+)': Cannot find field\.'''
    for match in re.finditer(pattern, raw_message):
        field, path = match.groups()
        parts = re.sub(r"\[\d+\]", "", path).split(".")
        if field in safe_fields and all(part in safe_path_parts for part in parts) and not re.search(r"\[\d{4,}\]", path):
            recognized.append(match.group())
    if recognized:
        message = "\n".join(dict.fromkeys(recognized))[:2000]
    elif "API key not valid" in raw_message or "API key expired" in raw_message:
        message = "The provider reports that the API key is invalid or expired."
    elif "location is not supported" in raw_message or "free tier is not available in your country" in raw_message:
        message = "The provider reports that the API or free tier is unavailable in this region."
    elif "not available for new users" in raw_message or "not available for new projects" in raw_message:
        message = "The provider reports that the configured model is unavailable to new users or projects."
    else:
        message = {
            "INVALID_ARGUMENT": "The provider rejected request arguments; unrecognized details omitted for privacy.",
            "FAILED_PRECONDITION": "The provider reports an unmet project or access precondition; details omitted for privacy.",
            "RESOURCE_EXHAUSTED": "The provider reports exhausted resources or quota; details omitted for privacy.",
        }.get(status, "The provider returned an error; unrecognized details omitted for privacy.")
    details = error.details if isinstance(error.details, dict) else {}
    detail = details.get("error", details)
    raw_code = detail.get("code") if isinstance(detail, dict) else None
    http_status = error.code if type(error.code) is int and 100 <= error.code <= 599 else 0
    code = raw_code if type(raw_code) is int and 0 <= raw_code <= 599 else http_status
    # A mistaken secrets setting must not turn a credential into metadata.
    safe_model = model if re.fullmatch(r"(?:models/)?(?:gemini|gemma)-[a-z0-9.-]+", model) else "[configured model omitted]"
    return ProviderDiagnostics(
        http_status=http_status, error_code=code, error_status=status, message=message,
        model=safe_model, sdk_version=genai.__version__, api_version=API_VERSION,
        operation="generateContent", schema_mode="response_json_schema",
        timeout_ms=60_000, maximum_attempts=1,
    )



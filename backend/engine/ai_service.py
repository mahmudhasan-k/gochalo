def normalize_whitespace(text: str) -> str:
    return " ".join(text.split())


_QUOTE_TRANSLATION = str.maketrans({"’":"'", "‘":"'", "“":'"', "”":'"', "–":"-", "—":"-", "。":"।"})


def _quotation_chars(text):
    # Source extractors commonly wrap words in Markdown emphasis markers.
    # Ignore only delimiter runs at formatting boundaries, retaining offsets so
    # a match still displays the exact unmodified source span. Internal symbols
    # such as multiplication a*b and snake_case identifiers stay significant.
    markup = [False] * len(text)
    for match in re.finditer(r"(?<!\w)(\*{1,3}|_{1,3})(?=\S)|(?<=\S)(\*{1,3}|_{1,3})(?!\w)", text):
        for index in range(match.start(), match.end()):
            markup[index] = True
    # Markdown list bullets are formatting too; do not confuse them with a
    # word-level asterisk such as the multiplication operator in source text.
    for match in re.finditer(r"(?m)^[ \t]{0,8}[*+-](?=[ \t]+)", text):
        for index in range(match.start(), match.end()):
            if text[index] in "*+-":
                markup[index] = True
    chars, offsets = [], []
    for index, original in enumerate(text):
        if markup[index]:
            continue
        for char in original.translate(_QUOTE_TRANSLATION).casefold():
            if char.isspace():
                if not chars or chars[-1] == " ":
                    continue
                char = " "
            chars.append(char); offsets.append(index)
    if chars and chars[-1] == " ":
        chars.pop(); offsets.pop()
    return "".join(chars), offsets


def _quotation_key(text: str) -> str:
    """Compare English typography/case and whitespace, never words or negation."""
    key, _ = _quotation_chars(text)
    if not re.search(r"[A-Za-z]", text):
        return key
    # Keep the historical Bangla danda contract used by delivery-rule matching.
    while key and (key[0].isspace() or unicodedata.category(key[0]).startswith("P") and key[0] != "।"):
        key = key[1:]
    while key and (key[-1].isspace() or unicodedata.category(key[-1]).startswith("P") and key[-1] != "।"):
        key = key[:-1]
    return key


def _quote_found(excerpt: str, source: str) -> bool:
    key = _quotation_key(excerpt)
    return bool(key) and key in _quotation_key(source)


def _original_excerpt(excerpt: str, source_text: str) -> str:
    """Return the exact original source span, including its original typography."""
    source, offsets = _quotation_chars(source_text)
    full, _ = _quotation_chars(excerpt)
    for key in dict.fromkeys((full, _quotation_key(excerpt))):
        if key and (start := source.find(key)) >= 0:
            first = offsets[start]
            last = offsets[start + len(key) - 1] + 1
            while first and source_text[first - 1] in "*_":
                first -= 1
            while last < len(source_text) and source_text[last] in "*_":
                last += 1
            return source_text[first:last]
    return excerpt


def _notice_key(text: str) -> str:
    """Only warning keys ignore terminal punctuation; quotation checks do not."""
    return normalize_whitespace(text).rstrip("।. ")



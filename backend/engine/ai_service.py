def _numeric_literals(text: str) -> set[str]:
    """Compare decimal digit runs only; never alter literal quotation matching.

    A conservative check for invented numeric details, not semantic entailment:
    shared numbers can still have the wrong meaning, unit, service or condition.
    Bangla/ASCII digits are equivalent here; punctuation and units are not inferred.
    """
    return {"".join(str(unicodedata.decimal(char)) for char in token) for token in re.findall(r"\d+", text)}


